/// An achievement and how close the learner is to it. Unlocked the first
/// time [value] reaches [target]; the unlock is then saved (learn_unlocks)
/// and stays even if the numbers later fall.
class Achievement {
  const Achievement(
    this.key,
    this.title,
    this.description,
    this.icon,
    this.target,
    this.value, {
    this.group = '',
  });
  final String key, title, description, group;
  final IconData icon;
  final num target;
  final num Function(Stats s) value;
}

